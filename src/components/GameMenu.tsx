import { useEffect, useState } from 'react';
import { FUEL_CELLS, SHIP_TIERS } from '../game/tiers';
import { TIER_BOOSTS } from '../game/spawnSchedule';
import { formatMoney, formatMultiplier } from '../game/money';
import type { GameActions, GameState } from '../game/useGameState';
import { Ship } from './space/Ship';
import { FuelCell } from './space/FuelCell';

type View = 'root' | 'howToPlay' | 'gameRules' | 'provablyFair' | 'gameLimits' | 'myBets';

const VIEW_TITLES: Record<Exclude<View, 'root'>, string> = {
  howToPlay: 'How To Play',
  gameRules: 'Game Rules',
  provablyFair: 'Provably Fair',
  gameLimits: 'Game Limits',
  myBets: 'My Bets',
};

function HowToPlayView() {
  return (
    <div className="menu-section">
      <ol className="menu-howto-list">
        <li>Choose a bet amount for either or both betting slots, then tap <strong>LAUNCH</strong> during the countdown.</li>
        <li>The multiplier climbs as your ship accelerates. Tap <strong>Cash Out</strong> before it's destroyed to win your bet × the multiplier.</li>
        <li>Want more? Move the mouse (or drag a finger) to fly the ship. Grab glowing fuel cells for a multiplier boost — your class can only carry cells smaller than itself, so bigger cells unlock as you upgrade.</li>
        <li>Dodge the asteroids — flying into one destroys the ship and every active bet instantly. If you don't steer, you can't hit one.</li>
        <li>Your ship upgrades from Scout to Mothership as the multiplier passes 2x, 5x, 10x and 25x.</li>
        <li>Set <strong>Auto</strong> → <strong>Cash out at</strong> to lock in automatically, or <strong>Auto-play</strong> to keep betting for several rounds.</li>
      </ol>
    </div>
  );
}

function GameRulesView({ state }: { state: GameState }) {
  return (
    <div className="menu-section">
      <p>
        Each player has two independent betting slots — each can carry a different bet amount and
        Auto Cash-Out value. Both slots share the same ship: if it hits an asteroid, every active slot's
        bet is lost together.
      </p>
      {state.limits && (
        <>
          <div className="menu-stat-row"><span>Min Bet</span><span>{state.limits.minBet.toFixed(2)}</span></div>
          <div className="menu-stat-row"><span>Max Bet</span><span>{state.limits.maxBet.toFixed(2)}</span></div>
          <div className="menu-stat-row"><span>Max Win</span><span>{state.limits.maxWin.toFixed(2)}</span></div>
        </>
      )}
      <p>
        Crash multipliers are generated by a cryptographically seeded, provably fair random number
        generator with a fixed house edge built into the algorithm itself — see Provably Fair for
        details.
      </p>
      <p>
        The fuel cell / asteroid layout each round is derived from the same public seed used for the crash
        multiplier, so what you see on screen is exactly what the server validates every pickup and
        asteroid hit against.
      </p>
      <p>Bets cannot be cancelled once placed. Disconnecting mid-round does not cancel an active bet — reconnect to see its outcome.</p>
    </div>
  );
}

function ProvablyFairView({ state }: { state: GameState }) {
  const f = state.fairness;
  const last = state.lastRoundFairness;
  return (
    <div className="menu-section">
      <p>
        Before each round starts, the server publishes a SHA-256 hash of a secret "server seed."
        That commits the server to a result before anyone places a bet — it cannot change the seed
        afterward to influence the outcome. The seed itself is revealed once the round crashes, so
        the crash point and fuel cell / asteroid layout can be independently recomputed and verified.
      </p>

      {f && (
        <>
          <div className="menu-subsection-title">Current Round</div>
          <div className="menu-stat-row"><span>Nonce</span><span>{f.nonce}</span></div>
          <div className="menu-seed-box">
            <div className="menu-seed-label">Server Seed Hash</div>
            <div className="menu-seed-value">{f.serverSeedHash}</div>
          </div>
          <div className="menu-seed-box">
            <div className="menu-seed-label">Client Seed</div>
            <div className="menu-seed-value">{f.clientSeed}</div>
          </div>
        </>
      )}

      {last ? (
        <>
          <div className="menu-subsection-title">Last Round — Revealed</div>
          <div className="menu-stat-row"><span>Nonce</span><span>{last.nonce}</span></div>
          <div className="menu-stat-row"><span>Crash Point</span><span>{formatMultiplier(last.crashMultiplier)}</span></div>
          <div className="menu-seed-box">
            <div className="menu-seed-label">Server Seed (revealed)</div>
            <div className="menu-seed-value">{last.serverSeed}</div>
          </div>
          <div className="menu-seed-box">
            <div className="menu-seed-label">Server Seed Hash</div>
            <div className="menu-seed-value">{last.serverSeedHash}</div>
          </div>
          <p>
            The server seed above was locked in before that round started — run SHA-256 on it and
            compare it to the hash. If they match, the outcome was set before any bets were placed
            and could not have been manipulated.
          </p>
        </>
      ) : (
        <p>After the next crash, the revealed server seed will appear here so you can verify the result independently.</p>
      )}
    </div>
  );
}

function GameLimitsView({ state }: { state: GameState }) {
  if (!state.limits) {
    return <div className="menu-section"><p>Loading…</p></div>;
  }
  return (
    <div className="menu-section">
      <div className="menu-stat-row"><span>Min Bet</span><span>{state.limits.minBet.toFixed(2)}</span></div>
      <div className="menu-stat-row"><span>Max Bet</span><span>{state.limits.maxBet.toFixed(2)}</span></div>
      <div className="menu-stat-row"><span>Max Win (per bet)</span><span>{state.limits.maxWin.toFixed(2)}</span></div>
    </div>
  );
}

/** Persisted bet history — fetched fresh from the server (GetMyBets) each time this view opens. */
function MyBetsView({ state, actions }: { state: GameState; actions: GameActions }) {
  useEffect(() => {
    actions.refreshMyBets();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  if (state.betHistory.length === 0) {
    return <div className="menu-section"><p>No bets yet — your history will show up here after your first round.</p></div>;
  }

  return (
    <div className="menu-section">
      <div className="mybets-list">
        {state.betHistory.map((bet, i) => {
          const won = bet.winAmount != null && bet.winAmount > 0;
          return (
            <div key={`${bet.roundId}-${bet.slotIndex}-${i}`} className="mybets-row">
              <div className="mybets-row-main">
                <span className="mybets-amount">{formatMoney(bet.amount, bet.currency)}</span>
                <span className={`mybets-outcome ${won ? 'win' : 'loss'}`}>
                  {won ? `+${formatMoney(bet.winAmount!, bet.currency)}` : '—'}
                </span>
              </div>
              <div className="mybets-row-meta">
                <span>{bet.cashedOutAt != null ? formatMultiplier(bet.cashedOutAt) : 'no cash-out'}</span>
                <span>{new Date(bet.placedAt).toLocaleString()}</span>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}

/** Burger menu — Paytable root view + drill-down sub-views (How To Play, Rules, Fairness, Limits, My Bets). */
export function GameMenu({ state, actions }: { state: GameState; actions: GameActions }) {
  const [view, setView] = useState<View>('root');

  if (view !== 'root') {
    return (
      <div className="legend-panel glass">
        <div className="menu-view-header">
          <button className="menu-back-btn" onClick={() => setView('root')}>← Back</button>
          <span className="menu-view-title">{VIEW_TITLES[view]}</span>
        </div>
        {view === 'howToPlay' && <HowToPlayView />}
        {view === 'gameRules' && <GameRulesView state={state} />}
        {view === 'provablyFair' && <ProvablyFairView state={state} />}
        {view === 'gameLimits' && <GameLimitsView state={state} />}
        {view === 'myBets' && <MyBetsView state={state} actions={actions} />}
      </div>
    );
  }

  return (
    <div className="legend-panel glass">
      <h2 className="legend-title">Ship Classes</h2>
      <div className="legend-rows">
        {SHIP_TIERS.slice(1).map((tier) => (
          <div key={tier.id} className="legend-row">
            <div className="legend-fish-box">
              <Ship shipClass={tier.id} width={26} thrust={0} />
            </div>
            <div className="legend-names">
              <span className="legend-name">{tier.name}</span>
              <span className="legend-tier">{tier.multiplier === 1 ? 'starting ship' : 'upgrades at'}</span>
            </div>
            <span className="legend-mult" style={{ color: tier.accent }}>
              {tier.multiplier.toFixed(0)}x
            </span>
          </div>
        ))}
      </div>

      <h2 className="legend-title">Fuel Cells</h2>
      <div className="legend-rows">
        {FUEL_CELLS.map((cell, i) => (
          <div key={cell.name} className="legend-row">
            <div className="legend-fish-box">
              <FuelCell tier={i} width={28} />
            </div>
            <div className="legend-names">
              <span className="legend-name">{cell.name}</span>
              <span className="legend-tier">needs {SHIP_TIERS[i + 1].name}+</span>
            </div>
            <span className="legend-mult" style={{ color: cell.color }}>
              +{TIER_BOOSTS[i].toFixed(2)}x
            </span>
          </div>
        ))}
      </div>

      <div className="legend-divider" />

      <nav className="menu-nav">
        <button className="menu-nav-link" onClick={() => setView('myBets')}>
          <span className="menu-nav-icon">🎟️</span>My Bets<span className="menu-nav-chevron">›</span>
        </button>
        <button className="menu-nav-link" onClick={() => setView('howToPlay')}>
          <span className="menu-nav-icon">📖</span>How To Play<span className="menu-nav-chevron">›</span>
        </button>
        <button className="menu-nav-link" onClick={() => setView('gameRules')}>
          <span className="menu-nav-icon">📋</span>Game Rules<span className="menu-nav-chevron">›</span>
        </button>
        <button className="menu-nav-link" onClick={() => setView('provablyFair')}>
          <span className="menu-nav-icon">🛡️</span>Provably Fair<span className="menu-nav-chevron">›</span>
        </button>
        <button className="menu-nav-link" onClick={() => setView('gameLimits')}>
          <span className="menu-nav-icon">💰</span>Game Limits<span className="menu-nav-chevron">›</span>
        </button>
      </nav>
    </div>
  );
}
